def test_columnar_windows_key_and_case_sensitive_paths():
    keys = CapturedPaths(meta())
    assert keys.key('C:\\DATA\\a') == keys.key('c:/data/a')
    assert keys.key('C:\\data\\ß') != keys.key('C:\\data\\ss')
    assert keys.key('C:\\data\\no-extension.') == keys.key('C:\\data\\no-extension')
    assert keys.key('C:\\data\\name. \\file') == keys.key('C:\\data\\name\\file')
    assert keys.key('\\\\?\\C:\\data\\literal.') != keys.key('C:\\data\\literal')
    sensitive = meta()
    sensitive['scope']['case_sensitive_roots'] = ['C:\\data']
    keys = CapturedPaths(sensitive)
    assert keys.key('C:\\data\\a') != keys.key('C:\\data\\A')


@pytest.mark.parametrize('mft',[True,False])
def test_columnar_space_date_csv_and_synthetic_walk_identity(tmp_path,mft):
    source=tmp_path/'dates.csv'
    with source.open('w',encoding='utf-8',newline='') as stream:
        writer=csv.writer(stream);writer.writerow(['File Name','Size','Allocated','Modified','Attributes','MFTRecNo'])
        writer.writerow(['C:\\data\\',20,8192,'2026 10 18 15:44:09',16,1])
        writer.writerow(['C:\\data\\a',10,4096,'2026 10 18 15:44:09',0,7])
        writer.writerow(['C:\\data\\b',10,4096,'2026 10 18 15:44:09',0,7])
    repo=Repository(tmp_path/'repo')
    scan=import_wiztree(source,meta(mft=mft),timezone_name='UTC',repository=repo)
    assert scan['summary']['logical']==20
    assert scan['summary']['allocated']==(4096 if mft else None)
    with MemorySession(repo) as session:
        rows=session.rows("SELECT * FROM read_parquet(?) WHERE kind='file'",[str(repo.path(scan))])
        assert all(r['modified']==1792338249 for r in rows)
        assert all(bool(r['identity'])==mft for r in rows)


