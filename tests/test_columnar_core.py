def legacy_fixture(root, rows):
    folder = root / 'data/history/scans'; folder.mkdir(parents=True)
    profile = {'roots': ['C:\\data'], 'strict_browsers': False, 'mft': True}
    scan = {'id': 36, 'profile': 'fixture', 'engine': 'wiztree', 'started': '2026-01-01T00:00:00+00:00',
            'finished': '2026-01-01T00:01:00+00:00', 'status': 'partial', 'config': json.dumps(profile),
            'summary': json.dumps({'data_warnings': ['Old measurement warning'], 'coverage': {'source': 'export', 'unknown_roots': ['C:\\data']}})}
    digest = hashlib.sha256()
    encoded = []
    for row in rows:
        line = (json.dumps([row.get(key) for key in FIELDS], ensure_ascii=False, separators=(',', ':')) + '\n').encode()
        encoded.append(line); digest.update(line)
    footer = {'records': len(rows), 'sha256': digest.hexdigest()}
    path = folder / 'scan-00000036.jsonl.gz'
    with gzip.open(path, 'wb') as stream:
        stream.write((json.dumps({'format': 'dgm-metadata-jsonl-1', 'columns': list(FIELDS), 'scan': scan}) + '\n').encode())
        for line in encoded:
            stream.write(line)
        stream.write((json.dumps({'end': footer}, separators=(',', ':')) + '\n').encode())
    catalog = {'schema': 1, 'tables': {'scans': [scan]}, 'logs': {'36': footer}}
    (folder.parent / 'catalog.json').write_text(json.dumps(catalog), encoding='utf-8')
    return path


def test_columnar_legacy_copy_is_verified_lossless_and_idempotent(tmp_path):
    source = tmp_path / 'legacy'
    rows = [entry('C:\\data\\a', 35), entry('C:\\data\\b', 7, None)]
    source_path = legacy_fixture(source, rows)
    before = source_path.read_bytes()
    repo = Repository(tmp_path / 'repo')
    result = import_legacy(source, [36], repository=repo)[0]
    assert result['summary']['logical'] == 42
    assert result['summary']['allocated'] is None
    assert 'Old measurement warning' in result['warnings']
    assert import_legacy(source, [36], repository=repo)[0]['already_imported']
    assert len(repo.list()) == 1
    assert source_path.read_bytes() == before
    assert not list(tmp_path.rglob('*.sqlite*'))


def test_columnar_snapshot_pin_blocks_delete(tmp_path):
    repo = Repository(tmp_path / 'repo')
    scan = import_entries([entry('C:\\data\\a')], meta(), repository=repo)
    with MemorySession(repo) as session:
        session.pin([scan])
        with pytest.raises(RuntimeError, match='đang được đọc'):
            repo.delete([scan['id']])
    assert repo.delete([scan['id']])['removed_bytes'] > 0
    assert not repo.list()
